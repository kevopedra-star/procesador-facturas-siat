CREATE OR REPLACE FUNCTION public.inicializar_matriz_liquidacion()
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    r RECORD;
BEGIN
    -- Limpiar la tabla física
    TRUNCATE TABLE public.mtodo;
    
    -- Recalcular para cada importación del cliente Minera San Cristóbal
    FOR r IN 
        SELECT DISTINCT n_referencia 
        FROM public.importaciones
        WHERE (razon_social ILIKE '%MINERA SAN CRISTOBAL%' OR nit_importador = '1020415021')
          AND n_referencia IS NOT NULL 
          AND n_referencia <> ''
    LOOP
        PERFORM public.recalcular_carpeta_matriz(r.n_referencia);
    END LOOP;
    
    -- Recalcular resumen
    PERFORM public.recalcular_resumen_mensual();
END;
$$;

-- Ejecutar la inicialización para popular la tabla física inmediatamente
SELECT public.inicializar_matriz_liquidacion();

