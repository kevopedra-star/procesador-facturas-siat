-- A. Extracción inteligente del NIT desde el enlace del QR (parámetro nit=...)
CREATE OR REPLACE FUNCTION public.extraer_nit_from_qr(qr_text text)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
    v_nit text;
BEGIN
    IF qr_text IS NULL OR qr_text = '' THEN
        RETURN NULL;
    END IF;
    
    IF qr_text LIKE '%nit=%' THEN
        v_nit := substring(qr_text from 'nit=([0-9]+)');
        IF v_nit IS NOT NULL THEN
            RETURN v_nit;
        END IF;
    END IF;
    
    IF qr_text LIKE '%|%' THEN
        RETURN split_part(qr_text, '|', 1);
    END IF;
    
    IF qr_text ~ '^[0-9]+$' THEN
        RETURN qr_text;
    END IF;
    
    RETURN NULL;
END;
$$;

-- B. Transformación de n_declaracion de importaciones (ej. DI-2026-543-2023821 -> 5432026D2023821)
CREATE OR REPLACE FUNCTION public.transformar_declaracion(decl_text text)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
    v_parts text[];
BEGIN
    IF decl_text IS NULL OR decl_text = '' OR decl_text = '-' THEN
        RETURN '-';
    END IF;
    
    decl_text := replace(trim(decl_text), ' ', '-');
    v_parts := string_to_array(decl_text, '-');
    
    IF array_length(v_parts, 1) = 4 THEN
        RETURN v_parts[3] || v_parts[2] || 'D' || v_parts[4];
    END IF;
    
    IF array_length(v_parts, 1) = 3 THEN
        RETURN v_parts[2] || v_parts[1] || 'D' || v_parts[3];
    END IF;
    
    RETURN regexp_replace(decl_text, '[^a-zA-Z0-9]', '', 'g');
END;
$$;

-- C. Comparación inteligente y limpia de declaraciones aduaneras
CREATE OR REPLACE FUNCTION public.comparar_declaraciones(decl_imp text, doc_fact text)
RETURNS boolean LANGUAGE plpgsql AS $$
DECLARE
    v_clean_imp text;
    v_clean_fact text;
BEGIN
    IF decl_imp IS NULL OR decl_imp = '' OR decl_imp = '-' OR doc_fact IS NULL OR doc_fact = '' OR doc_fact = '-' THEN
        RETURN FALSE;
    END IF;
    
    v_clean_imp := public.transformar_declaracion(decl_imp);
    v_clean_imp := regexp_replace(upper(trim(v_clean_imp)), '[^A-Z0-9]', '', 'g');
    v_clean_fact := regexp_replace(upper(trim(doc_fact)), '[^A-Z0-9]', '', 'g');
    
    RETURN (v_clean_imp = v_clean_fact OR position(v_clean_imp in v_clean_fact) > 0 OR position(v_clean_fact in v_clean_imp) > 0);
END;
$$;

-- D. Comparación inteligente y limpia de guías (ignora prefijos MAWB, HAWB, etc.)
CREATE OR REPLACE FUNCTION public.comparar_guias(guia_imp text, ref_fact text)
RETURNS boolean LANGUAGE plpgsql AS $$
DECLARE
    v_clean_imp text;
    v_clean_fact text;
BEGIN
    IF guia_imp IS NULL OR guia_imp = '' OR guia_imp = '-' OR ref_fact IS NULL OR ref_fact = '' OR ref_fact = '-' THEN
        RETURN FALSE;
    END IF;
    
    v_clean_imp := regexp_replace(upper(trim(guia_imp)), '[^A-Z0-9]', '', 'g');
    v_clean_fact := regexp_replace(upper(trim(ref_fact)), '[^A-Z0-9]', '', 'g');
    v_clean_fact := regexp_replace(v_clean_fact, '^(MAWB|HAWB|GUIA|AWB)', '', 'i');
    
    RETURN (v_clean_imp = v_clean_fact OR position(v_clean_imp in v_clean_fact) > 0 OR position(v_clean_fact in v_clean_imp) > 0);
END;
$$;

-- E. LÓGICA DE RECALCULACIÓN DE RESUMEN MENSUAL
CREATE OR REPLACE FUNCTION public.recalcular_resumen_mensual()
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    TRUNCATE TABLE public.resumen_mensual;
    
    INSERT INTO public.resumen_mensual (
        mes,
        total_comisiones,
        total_albo,
        total_albo_ip,
        total_guias,
        total_puertos,
        total_otros,
        total_facturas,
        total_general,
        updated_at
    )
    SELECT 
        mes,
        coalesce(sum(comision_bob), 0.00) as total_comisiones,
        coalesce(sum(albo_monto), 0.00) as total_albo,
        coalesce(sum(ip_monto), 0.00) as total_albo_ip,
        coalesce(sum(guias_monto), 0.00) as total_guias,
        coalesce(sum(puertos_monto), 0.00) as total_puertos,
        coalesce(sum(otros_monto), 0.00) as total_otros,
        coalesce(sum(coalesce(albo_monto, 0.00) + coalesce(ip_monto, 0.00) + coalesce(guias_monto, 0.00) + coalesce(puertos_monto, 0.00) + coalesce(otros_monto, 0.00)), 0.00) as total_facturas,
        coalesce(sum(coalesce(comision_bob, 0.00) + coalesce(albo_monto, 0.00) + coalesce(ip_monto, 0.00) + coalesce(guias_monto, 0.00) + coalesce(puertos_monto, 0.00) + coalesce(otros_monto, 0.00)), 0.00) as total_general,
        now()
    FROM public.mtodo
    WHERE mes <> '-'
    GROUP BY mes;
END;
$$;

-- F. LÓGICA DE RECALCULACIÓN DE CARPETA (Whitelisting y matching dinámico de NITs y Verificaciones)
CREATE OR REPLACE FUNCTION public.recalcular_carpeta_matriz(target_n_referencia text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v_importacion_id bigint;
    v_total_cif text;
    v_tipo_cambio numeric;
    v_tc_aplicado numeric;
    v_cif_bob numeric;
    v_cif_usd numeric;
    
    -- Variables para el cálculo de la comisión
    v_porcentaje_comision numeric;
    v_comision_fija numeric;
    v_comision_bob numeric;
    v_porcentaje_str text;
    
    -- variables para ALBO/DAB
    v_albo_cod text;
    v_albo_factura text;
    v_albo_fecha text;
    v_albo_enlace text;
    v_albo_monto numeric;
    v_albo_n_declaracion_imp text;
    v_albo_doc_aduanero_fac text;
    v_albo_verificado text;
    
    -- variables para IP
    v_ip_cod text;
    v_ip_factura text;
    v_ip_fecha text;
    v_ip_enlace text;
    v_ip_monto numeric;
    v_ip_examen_previo_imp text;
    v_ip_doc_aduanero_fac text;
    v_ip_verificado text;
    
    -- variables para GUIAS
    v_guias_cod text;
    v_guias_factura text;
    v_guias_fecha text;
    v_guias_enlace text;
    v_guias_monto numeric;
    v_guias_guia_embarque_imp text;
    v_guias_ref_guia_fac text;
    v_guias_verificado text;
    
    -- variables para PUERTOS
    v_puertos_comprobante text;
    v_puertos_fecha text;
    v_puertos_monto numeric;
    
    -- variables para Tributos
    v_gravamen numeric(15,2);
    v_iva numeric(15,2);
    v_total_tributos numeric(15,2);
    
    -- variables para OTROS
    v_otros_cod text;
    v_otros_factura text;
    v_otros_fecha text;
    v_otros_enlace text;
    v_otros_monto numeric;
    
    -- Datos de la importación
    v_fecha_aceptacion text;
    v_mes text;
    v_date date;
    v_nit_importador text;
    v_n_declaracion text;
    v_modalidad text;
    v_estado_liquidacion text;
    v_oi text;
    v_examen_previo text;
    v_guia_embarque text;
    
    -- Overrides manuales
    v_comision_manual numeric;
    v_dim_regularizada text;
    v_dim_reg_status text;
    
    -- Planilla Excel
    v_ref_excel text;
    v_fecha_excel text;
    v_debito_excel numeric(15,2);
BEGIN
    -- 1. Obtener detalles de la importación, filtrando SOLO por MINERA SAN CRISTOBAL S.A. o su NIT
    SELECT id, total_cif, tipo_cambio, fecha_aceptacion, n_declaracion, modalidad, estado_liquidacion, oi, nit_importador, examen_previo, guia_embarque,
           coalesce(nullif(regexp_replace(gravamen, '[^0-9.]', '', 'g'), ''), '0')::numeric,
           coalesce(nullif(regexp_replace(iva, '[^0-9.]', '', 'g'), ''), '0')::numeric,
           coalesce(nullif(regexp_replace(total_tributos, '[^0-9.]', '', 'g'), ''), '0')::numeric
    INTO v_importacion_id, v_total_cif, v_tipo_cambio, v_fecha_aceptacion, v_n_declaracion, v_modalidad, v_estado_liquidacion, v_oi, v_nit_importador, v_examen_previo, v_guia_embarque,
         v_gravamen, v_iva, v_total_tributos
    FROM public.importaciones
    WHERE n_referencia = target_n_referencia
      AND (razon_social ILIKE '%MINERA SAN CRISTOBAL%' OR nit_importador = '1020415021')
    LIMIT 1;
    
    IF v_importacion_id IS NULL THEN
        DELETE FROM public.mtodo WHERE interno = target_n_referencia;
        PERFORM public.recalcular_resumen_mensual();
        RETURN;
    END IF;
    
    -- 2. Calcular mes (abbreviación ENE-2026, JUL-2026, etc.) con parseador robusto
    BEGIN
        IF v_fecha_aceptacion IS NOT NULL AND v_fecha_aceptacion <> '' AND v_fecha_aceptacion <> '-' THEN
            IF v_fecha_aceptacion ~ '^[0-9]{4}-' THEN
                v_date := to_date(v_fecha_aceptacion, 'YYYY-MM-DD');
            ELSIF v_fecha_aceptacion ~ '^[0-9]{2}/' THEN
                v_date := to_date(v_fecha_aceptacion, 'DD/MM/YYYY');
            ELSE
                v_date := v_fecha_aceptacion::date;
            END IF;
            
            v_mes := CASE extract(month from v_date)
                WHEN 1 THEN 'ENE'
                WHEN 2 THEN 'FEB'
                WHEN 3 THEN 'MAR'
                WHEN 4 THEN 'ABR'
                WHEN 5 THEN 'MAY'
                WHEN 6 THEN 'JUN'
                WHEN 7 THEN 'JUL'
                WHEN 8 THEN 'AGO'
                WHEN 9 THEN 'SEP'
                WHEN 10 THEN 'OCT'
                WHEN 11 THEN 'NOV'
                WHEN 12 THEN 'DIC'
                ELSE '-'
            END || '-' || to_char(v_date, 'YYYY');
        ELSE
            v_mes := '-';
        END IF;
    EXCEPTION WHEN OTHERS THEN
        v_mes := '-';
    END;

    -- 3. Calcular valores financieros básicos
    v_tc_aplicado := coalesce(nullif(v_tipo_cambio, 0), 6.96);
    v_cif_bob := coalesce(nullif(regexp_replace(v_total_cif, '[^0-9.]', '', 'g'), ''), '0')::numeric;
    v_cif_usd := v_cif_bob / v_tc_aplicado;
    
    -- Buscar comisión en tablas configurables
    SELECT comision_fija, tipo_operacion 
    INTO v_comision_fija, v_porcentaje_str
    FROM public.config_comisiones_especiales
    WHERE v_oi ILIKE '%' || tipo_operacion || '%'
    LIMIT 1;
    
    IF FOUND THEN
        v_comision_bob := v_comision_fija;
        v_porcentaje_str := 'Fijo: ' || v_porcentaje_str;
    ELSE
        SELECT porcentaje_comision, comision_fija 
        INTO v_porcentaje_comision, v_comision_fija
        FROM public.config_comisiones_minera
        WHERE v_cif_usd >= cif_usd_min AND v_cif_usd <= cif_usd_max
        LIMIT 1;
        
        IF NOT FOUND THEN
            v_comision_bob := 600.00;
            v_porcentaje_str := 'Tarifa Fija';
        ELSIF v_comision_fija > 0 THEN
            v_comision_bob := v_comision_fija;
            v_porcentaje_str := 'Tarifa Fija';
        ELSE
            v_comision_bob := v_cif_bob * v_porcentaje_comision;
            v_porcentaje_str := to_char(v_porcentaje_comision * 100, 'FM990.00') || '%';
        END IF;
    END IF;
    
    -- Aplicar override de ajuste manual de comisión si existe
    SELECT comision INTO v_comision_manual
    FROM public.historial_datos_minera
    WHERE dim_id = v_importacion_id OR interno = target_n_referencia
    LIMIT 1;
    
    IF v_comision_manual IS NOT NULL THEN
        v_comision_bob := v_comision_manual;
        v_porcentaje_str := 'Manual';
    END IF;
    
    -- Obtener estado de regularización
    SELECT dim_regularizada INTO v_dim_regularizada
    FROM public.regularizaciones_dims
    WHERE interno = target_n_referencia
    LIMIT 1;
    
    IF FOUND AND v_dim_regularizada = 'OK' THEN
        v_dim_reg_status := 'OK';
    ELSE
        v_dim_reg_status := '-';
    END IF;
    
    -- 4. Consolidar ALBO / DAB (Extrayendo el NIT desde enlace_qr / f.nit para relacionar el código)
    SELECT 
        sum(f.monto),
        string_agg(f.n_factura, ', '),
        string_agg(f.fecha, ', '),
        string_agg(coalesce(f.codigo_qr, '-'), ', '),
        string_agg(distinct coalesce(cn.codigo, public.extraer_nit_from_qr(f.codigo_qr), f.nit, 'S/C'), ', '),
        string_agg(distinct coalesce(f.doc_aduanero, '-'), ', ')
    INTO v_albo_monto, v_albo_factura, v_albo_fecha, v_albo_enlace, v_albo_cod, v_albo_doc_aduanero_fac
    FROM public.facturas f
    LEFT JOIN public.config_nits cn ON cn.nit = coalesce(public.extraer_nit_from_qr(f.codigo_qr), f.nit)
    WHERE f.importacion_id = v_importacion_id
      AND (((f.tipo ILIKE '%ALBO%' AND f.tipo NOT ILIKE '%IP%' AND f.tipo NOT ILIKE '%INSPECCION%') OR f.tipo ILIKE '%DAB%'));

    -- Transformación y Verificación ALBO
    v_albo_n_declaracion_imp := public.transformar_declaracion(v_n_declaracion);
    
    IF v_modalidad ILIKE '%ANTICIPAD%' THEN
        v_albo_verificado := '-';
    ELSIF v_albo_monto IS NULL OR v_albo_monto = 0 THEN
        v_albo_verificado := '-';
    ELSIF public.comparar_declaraciones(v_n_declaracion, v_albo_doc_aduanero_fac) THEN
        v_albo_verificado := 'VERIFICADO';
    ELSE
        v_albo_verificado := 'NO VERIFICADO';
    END IF;

    -- 5. Consolidar Inspección Previa (IP)
    SELECT 
        sum(f.monto),
        string_agg(f.n_factura, ', '),
        string_agg(f.fecha, ', '),
        string_agg(coalesce(f.codigo_qr, '-'), ', '),
        string_agg(distinct coalesce(cn.codigo, public.extraer_nit_from_qr(f.codigo_qr), f.nit, 'S/C'), ', '),
        string_agg(distinct coalesce(f.doc_aduanero, '-'), ', ')
    INTO v_ip_monto, v_ip_factura, v_ip_fecha, v_ip_enlace, v_ip_cod, v_ip_doc_aduanero_fac
    FROM public.facturas f
    LEFT JOIN public.config_nits cn ON cn.nit = coalesce(public.extraer_nit_from_qr(f.codigo_qr), f.nit)
    WHERE f.importacion_id = v_importacion_id
      AND (f.tipo ILIKE '%ALBO IP%' OR f.tipo ILIKE '%INSPECCION%');

    -- Estandarización y Verificación IP
    v_ip_examen_previo_imp := coalesce(v_examen_previo, '-');
    
    IF v_ip_monto IS NULL OR v_ip_monto = 0 THEN
        v_ip_verificado := '-';
    ELSIF v_ip_examen_previo_imp = '-' THEN
        v_ip_verificado := 'SIN EXAMEN PREVIO';
    ELSIF position(v_ip_examen_previo_imp in coalesce(v_ip_doc_aduanero_fac, '')) > 0 THEN
        v_ip_verificado := 'VERIFICADO';
    ELSE
        v_ip_verificado := 'NO VERIFICADO';
    END IF;

    -- 6. Consolidar Guías
    SELECT 
        sum(f.monto),
        string_agg(f.n_factura, ', '),
        string_agg(f.fecha, ', '),
        string_agg(coalesce(f.codigo_qr, '-'), ', '),
        string_agg(distinct coalesce(cn.codigo, public.extraer_nit_from_qr(f.codigo_qr), f.nit, 'S/C'), ', '),
        string_agg(distinct coalesce(f.ref_guia, '-'), ', ')
    INTO v_guias_monto, v_guias_factura, v_guias_fecha, v_guias_enlace, v_guias_cod, v_guias_ref_guia_fac
    FROM public.facturas f
    LEFT JOIN public.config_nits cn ON cn.nit = coalesce(public.extraer_nit_from_qr(f.codigo_qr), f.nit)
    WHERE f.importacion_id = v_importacion_id
      AND (f.tipo ILIKE '%GUIA%');

    -- Estandarización y Verificación GUÍA
    v_guias_guia_embarque_imp := coalesce(v_guia_embarque, '-');
    
    IF v_modalidad ILIKE '%ANTICIPAD%' THEN
        v_guias_verificado := '-';
    ELSIF v_guias_monto IS NULL OR v_guias_monto = 0 THEN
        v_guias_verificado := '-';
    ELSIF v_guias_guia_embarque_imp = '-' THEN
        v_guias_verificado := 'SIN GUIA EMBARQUE';
    ELSIF public.comparar_guias(v_guias_guia_embarque_imp, v_guias_ref_guia_fac) THEN
        v_guias_verificado := 'VERIFICADO';
    ELSE
        v_guias_verificado := 'NO VERIFICADO';
    END IF;

    -- 7. Consolidar Puertos
    SELECT 
        sum(g.monto),
        string_agg(g.comprobante, ', '),
        string_agg(g.fecha, ', ')
    INTO v_puertos_monto, v_puertos_comprobante, v_puertos_fecha
    FROM public.gastos_puertos_manual g
    WHERE g.importacion_id = v_importacion_id;

    -- 8. Consolidar Otros
    SELECT 
        sum(f.monto),
        string_agg(f.n_factura, ', '),
        string_agg(f.fecha, ', '),
        string_agg(coalesce(f.codigo_qr, '-'), ', '),
        string_agg(distinct coalesce(cn.codigo, public.extraer_nit_from_qr(f.codigo_qr), f.nit, 'S/C'), ', ')
    INTO v_otros_monto, v_otros_factura, v_otros_fecha, v_otros_enlace, v_otros_cod
    FROM public.facturas f
    LEFT JOIN public.config_nits cn ON cn.nit = coalesce(public.extraer_nit_from_qr(f.codigo_qr), f.nit)
    WHERE f.importacion_id = v_importacion_id
      AND NOT (((f.tipo ILIKE '%ALBO%' AND f.tipo NOT ILIKE '%IP%' AND f.tipo NOT ILIKE '%INSPECCION%') OR f.tipo ILIKE '%DAB%'))
      AND NOT (f.tipo ILIKE '%ALBO IP%' OR f.tipo ILIKE '%INSPECCION%')
      AND NOT (f.tipo ILIKE '%GUIA%');

    -- 8.5 Obtener datos de planilla excel
    SELECT ref_excel, fecha_excel, debito_excel INTO v_ref_excel, v_fecha_excel, v_debito_excel
    FROM public.historial_datos_minera
    WHERE interno = target_n_referencia
    LIMIT 1;

    -- 9. Insertar o Actualizar registro en la tabla física "mtodo"
    INSERT INTO public.mtodo (
        interno, importacion_id, fecha_dim, mes, nit_cliente, dim_n_ro, modalidad, dim_reg, oi,
        tipo_cambio, cif_usd, porcentaje_comision, valor_cif_bs, comision_bob,
        gravamen, iva, total_tributos,
        
        -- PLANILLA EXCEL
        ref_excel, fecha_excel, debito_excel,
        
        -- ALBO / DAB
        albo_monto, albo_factura, albo_fecha, albo_enlace, albo_cod,
        albo_n_declaracion_imp, albo_doc_aduanero_fac, albo_verificado,
        
        -- INSPECCION PREVIA (IP)
        ip_monto, ip_factura, ip_fecha, ip_enlace, ip_cod,
        ip_examen_previo_imp, ip_doc_aduanero_fac, ip_verificado,
        
        -- GUÍAS
        guias_monto, guias_factura, guias_fecha, guias_enlace, guias_cod,
        guias_guia_embarque_imp, guias_ref_guia_fac, guias_verificado,
        
        -- PUERTOS
        puertos_monto, puertos_comprobante, puertos_fecha,
        
        -- OTROS
        otros_monto, otros_factura, otros_fecha, otros_enlace, otros_cod,
        updated_at
    ) VALUES (
        target_n_referencia,
        v_importacion_id,
        v_fecha_aceptacion,
        v_mes,
        coalesce(v_nit_importador, '1020415021'),
        v_n_declaracion,
        v_modalidad,
        v_dim_reg_status,
        v_oi,
        coalesce(to_char(v_tc_aplicado, 'FM9990.00'), '-'),
        coalesce(to_char(v_cif_usd, 'FM9999990.00'), '-'),
        v_porcentaje_str,
        coalesce(v_total_cif, '-'),
        v_comision_bob,
        v_gravamen, v_iva, v_total_tributos,
        
        -- PLANILLA EXCEL
        v_ref_excel, v_fecha_excel, v_debito_excel,
        
        -- ALBO
        v_albo_monto, v_albo_factura, v_albo_fecha, v_albo_enlace, v_albo_cod,
