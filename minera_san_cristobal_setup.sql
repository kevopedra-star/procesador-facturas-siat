CREATE OR REPLACE FUNCTION public.tg_recalcular_matriz_nits_modificados()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    r RECORD;
    v_nit text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_nit := OLD.nit;
    ELSE
        v_nit := NEW.nit;
    END IF;

    -- Recalcular solo las carpetas que tienen facturas con este NIT
    FOR r IN 
        SELECT DISTINCT imp.n_referencia 
        FROM public.importaciones imp
        JOIN public.facturas f ON f.importacion_id = imp.id
        WHERE (f.nit = v_nit OR public.extraer_nit_from_qr(f.codigo_qr) = v_nit)
          AND imp.n_referencia IS NOT NULL
          AND imp.n_referencia <> ''
    LOOP
        PERFORM public.recalcular_carpeta_matriz(r.n_referencia);
    END LOOP;
    
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    ELSE
        RETURN NEW;
    END IF;
END;
$$;

