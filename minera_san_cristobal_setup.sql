-- Triggers de overrides manuales (para reflejar cambios de comision o regularizacion de inmediato)
CREATE OR REPLACE FUNCTION public.tg_recalcular_matriz_overrides()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.interno IS NOT NULL THEN
            PERFORM public.recalcular_carpeta_matriz(OLD.interno);
        END IF;
        RETURN OLD;
    ELSE
        IF NEW.interno IS NOT NULL THEN
            PERFORM public.recalcular_carpeta_matriz(NEW.interno);
        END IF;
        RETURN NEW;
    END IF;
END;
$$;

