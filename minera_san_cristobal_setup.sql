CREATE OR REPLACE FUNCTION public.tg_recalcular_matriz_importaciones()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM public.recalcular_carpeta_matriz(OLD.n_referencia);
        RETURN OLD;
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.n_referencia IS DISTINCT FROM NEW.n_referencia THEN
            PERFORM public.recalcular_carpeta_matriz(OLD.n_referencia);
        END IF;
        PERFORM public.recalcular_carpeta_matriz(NEW.n_referencia);
        RETURN NEW;
    ELSE
        PERFORM public.recalcular_carpeta_matriz(NEW.n_referencia);
        RETURN NEW;
    END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_recalcular_matriz_importaciones ON public.importaciones;
CREATE TRIGGER trg_recalcular_matriz_importaciones
AFTER INSERT OR UPDATE OR DELETE ON public.importaciones
FOR EACH ROW EXECUTE FUNCTION public.tg_recalcular_matriz_importaciones();

