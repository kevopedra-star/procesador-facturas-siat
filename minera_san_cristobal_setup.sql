        IF v_n_ref IS NOT NULL THEN
            PERFORM public.recalcular_carpeta_matriz(v_n_ref);
        END IF;
        
        IF TG_OP = 'UPDATE' AND OLD.importacion_id IS DISTINCT FROM NEW.importacion_id THEN
            SELECT n_referencia INTO v_n_ref FROM public.importaciones WHERE id = OLD.importacion_id;
            IF v_n_ref IS NOT NULL THEN
                PERFORM public.recalcular_carpeta_matriz(v_n_ref);
